#!/usr/bin/env node
// Run: node --import tsx scripts/sync-model-catalog.mjs [downloaded-api.json]
// TypeScript output is included by tsup's bundle:false build.
import fs from "node:fs/promises";
import { createRequire } from "node:module";
import { format, resolveConfig } from "prettier";
const { CATALOG_URL, catalogSchema } = createRequire(import.meta.url)(
  "../src/main/ai/catalog-schema.ts",
);

const raw = process.argv[2]
  ? JSON.parse(await fs.readFile(process.argv[2], "utf8"))
  : await (async () => {
      const response = await fetch(CATALOG_URL, {
        signal: AbortSignal.timeout(8_000),
        headers: { "User-Agent": "Trident" },
      });
      if (!response.ok) throw new Error(`HTTP ${response.status}`);
      return response.json();
    })();
const providers = catalogSchema.parse(raw);
const snapshot = {
  source: CATALOG_URL,
  fetched_at: new Date().toISOString(),
  providers,
};
const destination = new URL(
  "../src/main/ai/catalog/bundled-catalog.ts",
  import.meta.url,
);
await fs.mkdir(new URL(".", destination), { recursive: true });
await fs.writeFile(
  destination,
  await format(
    `// AUTO-GENERATED by scripts/sync-model-catalog.mjs. Do not edit.\n// Source: ${CATALOG_URL} (MIT; see bundled notices).\nimport type { CatalogSnapshot } from "../catalog-schema.js";\n\nexport const BUNDLED_CATALOG: CatalogSnapshot = ${JSON.stringify(snapshot, null, 2)};\n`,
    {
      ...(await resolveConfig(destination.pathname)),
      parser: "typescript",
    },
  ),
);
console.log(
  `Bundled ${Object.values(providers).reduce((sum, provider) => sum + Object.keys(provider.models).length, 0)} models from models.dev.`,
);
